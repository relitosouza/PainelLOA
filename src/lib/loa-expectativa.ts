export function normalizeLoaExpectativaSecretaria(value: string) {
  return value
    .toLocaleLowerCase("pt-BR")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/\s+/g, " ")
    .replace(/\s*[-—–]\s*/g, "-")
    .trim();
}
