function normalizeDescription(value: string) {
  return value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[“”"]/g, "")
    .replace(/\s+/g, " ")
    .trim()
    .toLocaleUpperCase("pt-BR");
}

const descriptionsByCode = new Map<string, string>();
const knownParentCodes = new Set<string>();
const subelementsByParent = new Map<string, Set<string>>();
const subelementCodesByParent = new Map<string, Map<string, string>>();

for (const rawLine of RAW_EXPENSE_CATALOG.split(/\n/)) {
  const line = rawLine.trim();
  const match = line.match(/^(\d\.\d\.\d{2}\.\d{2}\.\d{2})\s+(.+)$/);
  if (!match) continue;
  const [, code, description] = match;
  descriptionsByCode.set(code, description.trim());
  const parent = `${code.slice(0, 10)}00`;
  knownParentCodes.add(parent);
  const descriptions = subelementsByParent.get(parent) ?? new Set<string>();
  descriptions.add(normalizeDescription(description));
  subelementsByParent.set(parent, descriptions);
  const codes = subelementCodesByParent.get(parent) ?? new Map<string, string>();
  codes.set(normalizeDescription(description), code);
  subelementCodesByParent.set(parent, codes);
}

export function extractExpenseCode(value: string) {
  return value.match(/\b\d\.\d\.\d{2}\.\d{2}\.\d{2}\b/)?.[0] ?? null;
}

export function expenseCodeDescription(code: string) {
  return descriptionsByCode.get(code) ?? null;
}

export function validateExpenseNature(value: string): ClassificationValidation {
  const code = extractExpenseCode(value);
  if (!value.trim()) return { code: null, valid: false, reason: "missing" };
  if (!code || (!descriptionsByCode.has(code) && !knownParentCodes.has(code))) {
    return { code, valid: false, reason: "invalid-code" };
  }
  return { code, valid: true, reason: "valid" };
}

export function validateExpenseSubelement(expenseNature: string, subelement: string) {
  const parent = extractExpenseCode(expenseNature);
  if (!subelement.trim()) return { valid: false, reason: "missing" as const };
  const subelementCode = extractExpenseCode(subelement);
  if (subelementCode) {
    return descriptionsByCode.has(subelementCode)
      ? { valid: true, reason: "valid" as const }
      : { valid: false, reason: "invalid-code" as const };
  }
  const descriptions = parent ? subelementsByParent.get(parent) : undefined;
  return descriptions?.has(normalizeDescription(subelement))
    ? { valid: true, reason: "valid" as const }
    : { valid: false, reason: "description-not-found" as const };
}

export function resolveExpenseSubelementCode(expenseNature: string, subelement: string) {
  const explicitCode = extractExpenseCode(subelement);
  if (explicitCode && descriptionsByCode.has(explicitCode)) return explicitCode;
  const parent = extractExpenseCode(expenseNature);
  if (!parent) return null;
  return subelementCodesByParent.get(parent)?.get(normalizeDescription(subelement)) ?? null;
}

export function classificationLabel(level: "category" | "group" | "modality", code: string) {
  if (level === "category") return EXPENSE_CATEGORY_LABELS[code] ?? "Categoria não cadastrada";
  if (level === "group") return EXPENSE_GROUP_LABELS[code] ?? "Grupo não cadastrado";
  return APPLICATION_MODALITY_LABELS[code] ?? "Modalidade não cadastrada";
}
